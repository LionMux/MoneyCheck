function normalize(s: string): string {
  return s.toLowerCase().replace(/ё/g, "е").trim();
}

/**
 * Находит подходящую категорию пользователя по внешнему тексту (из 2GIS или имени мерчанта).
 *
 * @param externalCategory  - категория из 2GIS (или null)
 * @param merchantName      - нормализованное название мерчанта
 * @param userCategories    - список категорий пользователя
 * @returns найденная категория или последняя в списке
 */
export function matchCategory(
  externalCategory: string | null,
  merchantName: string,
  userCategories: Category[],
): Category {
  const expenseCategories = userCategories.filter(c => c.type === "expense");
  const pool = expenseCategories.length > 0 ? expenseCategories : userCategories;

  if (pool.length === 0) throw new Error("No categories available");

  const haystack = [externalCategory, merchantName]
    .filter(Boolean)
    .map(s => normalize(s!));

  // 1. Прямое совпадение названия категории пользователя
  for (const cat of pool) {
    const catNorm = normalize(cat.name);
    if (haystack.some(h => h.includes(catNorm) || catNorm.includes(h))) {
      return cat;
    }
  }

  // 2. Через словарь синонимов
  for (const [key, keywords] of Object.entries(SYNONYM_MAP)) {
    const hit = haystack.some(h => h.includes(key));
    if (!hit) continue;

    for (const kw of keywords) {
      const found = pool.find(cat => normalize(cat.name).includes(kw));
      if (found) return found;
    }
  }

  // 3. Fallback — последняя категория
  return pool[pool.length - 1];
}
